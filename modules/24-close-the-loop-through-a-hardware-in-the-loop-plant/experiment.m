%% Read: a HIL loop is a timed exchange, not just a plant equation
% P23 separated requested, applied, and measured motion. P24 puts a
% timestamped software boundary between a controller and a virtual plant:
% measurement packet -> controller -> command packet -> watchdog -> plant.
% This makes interface timing visible without claiming physical HIL evidence.

%% Make one prediction before the baseline
% If every packet arrives but one-way latency grows, which changes first:
% measurement age, applied-force timing, or the plant trajectory?

%% Visualize the deterministic baseline position loop
baseline = model(0.05,0.01,0.2,0,Inf,1.5,0.01,8);
fprintf(['Baseline: tracking RMS %.4f m, integral absolute error ' ...
    '%.4f m*s, maximum measurement age %.3f s, watchdog %.3f s.\n'], ...
    baseline.trackingRmsM,baseline.integratedAbsoluteErrorMSec, ...
    baseline.maximumMeasurementAgeSec,baseline.watchdogDurationSec);

figure('Name','P24 baseline virtual plant position');
plot(baseline.timeSec,baseline.referencePositionM,'k--', ...
    'LineWidth',1.4,'DisplayName','Reference position');
hold on;
plot(baseline.timeSec,baseline.positionM,'b-', ...
    'LineWidth',1.8,'DisplayName','Virtual plant position');
hold off; grid on;
xlabel('Virtual time (s)'); ylabel('Position (m)');
title('Baseline: the loop crosses two timestamped transport paths');
legend('Location','best');

%% Visualize the complementary protocol view
figure('Name','P24 baseline protocol timing');
subplot(2,1,1);
plot(baseline.timeSec,baseline.measurementAgeSec,'m-', ...
    'LineWidth',1.6);
grid on; xlabel('Virtual time (s)');
ylabel('Measurement age (s)');
title('The controller acts on the newest delivered timestamp');
subplot(2,1,2);
plot(baseline.timeSec,baseline.controllerForceN,'c--', ...
    'LineWidth',1.3,'DisplayName','Controller request');
hold on;
plot(baseline.timeSec,baseline.appliedForceN,'b-', ...
    'LineWidth',1.7,'DisplayName','Plant-applied force');
hold off; grid on;
xlabel('Virtual time (s)'); ylabel('Force (N)');
title('Transport and watchdog separate requested from applied force');
legend('Location','best');

%% Read the mechanism: timestamps and held values close the loop
% The controller runs every T_c seconds. A measurement generated by the
% virtual plant arrives L seconds later, and its command arrives after
% another L seconds. Between valid command packets the plant holds the last
% delivered force. If its command age reaches T_w, the watchdog applies
% zero force. The plant itself never pauses while software waits.

%% Move lever 1: sweep only one-way transport latency
latencyValuesSec = [0.01 0.02 0.04 0.06 0.08];
latencyTrackingRmsM = zeros(size(latencyValuesSec));
latencyMaximumMeasurementAgeSec = zeros(size(latencyValuesSec));
latencyPeakPositionM = zeros(size(latencyValuesSec));
for k = 1:numel(latencyValuesSec)
    changed = model(0.05,latencyValuesSec(k),0.2,0,Inf,1.5,0.01,8);
    assert(changed.controllerPeriodSec == 0.05 && ...
        changed.watchdogTimeoutSec == 0.2 && ...
        changed.commandDropEveryN == 0 && isinf(changed.cancelAtSec) && ...
        changed.plantMassKg == 1.5 && changed.timeStepSec == 0.01 && ...
        changed.durationSec == 8, ...
        'Latency sweep changed a non-swept input.');
    latencyTrackingRmsM(k) = changed.trackingRmsM;
    latencyMaximumMeasurementAgeSec(k) = ...
        changed.maximumMeasurementAgeSec;
    latencyPeakPositionM(k) = changed.peakAbsPositionM;
end
assert(all(diff(latencyMaximumMeasurementAgeSec) > 0), ...
    'More transport latency must increase the maximum timestamp age.');
figure('Name','P24 one-way-latency sweep');
subplot(3,1,1);
plot(latencyValuesSec,latencyMaximumMeasurementAgeSec,'mo-', ...
    'LineWidth',1.7); grid on;
xlabel('One-way latency (s)'); ylabel('Maximum age (s)');
title('Sweep 1 changed view: delivered measurements become older');
subplot(3,1,2);
plot(latencyValuesSec,latencyTrackingRmsM,'bs-', ...
    'LineWidth',1.7); grid on;
xlabel('One-way latency (s)'); ylabel('Tracking RMS (m)');
title('Stale feedback changes the closed-loop trajectory');
subplot(3,1,3);
plot(latencyValuesSec,latencyPeakPositionM,'kd-', ...
    'LineWidth',1.7); grid on;
xlabel('One-way latency (s)'); ylabel('Peak |position| (m)');
title('Latency can spend closed-loop stability reserve');

%% Explain lever 1 from packet timestamps
% Moving L changes neither the controller schedule nor the plant. It moves
% the delivery ticks on both transport paths. The age plot changes before
% the mechanical state because the plant responds only after delayed data
% changes a delayed command.

%% Reset, then move lever 2: sweep only controller period
controllerPeriodValuesSec = [0.02 0.04 0.05 0.1 0.2];
periodTrackingRmsM = zeros(size(controllerPeriodValuesSec));
periodMaximumMeasurementAgeSec = zeros(size(controllerPeriodValuesSec));
periodCommandPacketCount = zeros(size(controllerPeriodValuesSec));
for k = 1:numel(controllerPeriodValuesSec)
    changed = model(controllerPeriodValuesSec(k),0.01,0.2,0, ...
        Inf,1.5,0.01,8);
    assert(changed.oneWayLatencySec == 0.01 && ...
        changed.watchdogTimeoutSec == 0.2 && ...
        changed.commandDropEveryN == 0 && isinf(changed.cancelAtSec) && ...
        changed.plantMassKg == 1.5 && changed.timeStepSec == 0.01 && ...
        changed.durationSec == 8, ...
        'Controller-period sweep changed a non-swept input.');
    periodTrackingRmsM(k) = changed.trackingRmsM;
    periodMaximumMeasurementAgeSec(k) = ...
        changed.maximumMeasurementAgeSec;
    periodCommandPacketCount(k) = changed.commandPacketSentCount;
end
assert(all(diff(periodCommandPacketCount) < 0) && ...
    all(diff(periodMaximumMeasurementAgeSec) > 0), ...
    'A slower controller must send fewer commands and use older samples.');
figure('Name','P24 controller-period sweep');
subplot(3,1,1);
plot(controllerPeriodValuesSec,periodCommandPacketCount,'co-', ...
    'LineWidth',1.7); grid on;
xlabel('Controller period (s)'); ylabel('Command packets (count)');
title('Sweep 2 changed view: slower release means fewer updates');
subplot(3,1,2);
plot(controllerPeriodValuesSec,periodMaximumMeasurementAgeSec,'ms-', ...
    'LineWidth',1.7); grid on;
xlabel('Controller period (s)'); ylabel('Maximum age (s)');
title('A longer held sample is older before the next delivery');
subplot(3,1,3);
plot(controllerPeriodValuesSec,periodTrackingRmsM,'bd-', ...
    'LineWidth',1.7); grid on;
xlabel('Controller period (s)'); ylabel('Tracking RMS (m)');
title('Coarse feedback eventually degrades the mechanical response');

%% Explain lever 2 from release rate, not plotting density
% Moving T_c changes when the controller reads its latest packet and sends
% a force request. The plant integration step stays 0.01 s in every run, so
% the changed view comes from held feedback, not a coarser plant solver.

%% Deliberately broken case: drop every second command until watchdog trips
% The broken case violates the continuous-command-stream assumption. The
% receiver keeps a command only until its age reaches 0.12 s, then applies
% zero force. Removing only the drop schedule restores continuous delivery.
broken = model(0.1,0.04,0.12,2,Inf,1.5,0.01,8);
dropRecovered = model(0.1,0.04,0.12,0,Inf,1.5,0.01,8);
assert(broken.commandPacketDroppedCount > 30 && ...
    broken.watchdogDurationSec > 3 && ...
    dropRecovered.commandPacketDroppedCount == 0 && ...
    dropRecovered.watchdogDurationSec < 0.2, ...
    'Command loss must trip the watchdog and no-drop recovery must clear it.');
figure('Name','P24 broken command-stream case');
subplot(2,1,1);
plot(broken.timeSec,broken.positionM,'b-', ...
    'LineWidth',1.7,'DisplayName','Plant position');
hold on;
plot(broken.timeSec,broken.referencePositionM,'k--', ...
    'LineWidth',1.3,'DisplayName','Reference position');
hold off; grid on;
xlabel('Virtual time (s)'); ylabel('Position (m)');
title('Broken assumption: alternate commands never reach the plant');
legend('Location','best');
subplot(2,1,2);
stairs(broken.timeSec,double(broken.watchdogTimedOut),'r-', ...
    'LineWidth',1.6,'DisplayName','Watchdog active');
hold on;
stairs(broken.timeSec,double(broken.commandPacketDropped),'k:', ...
    'LineWidth',1.4,'DisplayName','Command dropped');
hold off; grid on; ylim([-0.1 1.1]);
xlabel('Virtual time (s)'); ylabel('Protocol state (0 or 1)');
title('Recognizable symptom: stale command is replaced by safe zero');
legend('Location','best');

%% Cancel, roll to safe zero, and recover with a fresh isolated run
cancelledRun = model(0.05,0.01,0.2,0,4.01,1.5,0.01,8);
recovered = model(0.05,0.01,0.2,0,Inf,1.5,0.01,8);
cancellationIndex = find(cancelledRun.cancelled,1,'first');
assert(abs(cancelledRun.timeSec(cancellationIndex)-4.01) < 1e-12 && ...
    cancelledRun.commandPacketSent(cancellationIndex-1) && ...
    baseline.commandPacketDelivered(cancellationIndex) && ...
    all(cancelledRun.appliedForceN(cancellationIndex:end) == 0) && ...
    ~any(cancelledRun.commandPacketDelivered(cancellationIndex:end)) && ...
    isequaln(recovered,baseline), ...
    'Cancellation must win same-tick delivery and a fresh run must recover.');
figure('Name','P24 cancellation and safe-zero rollback');
plot(cancelledRun.timeSec,cancelledRun.appliedForceN,'b-', ...
    'LineWidth',1.7,'DisplayName','Applied force');
hold on;
stairs(cancelledRun.timeSec,double(cancelledRun.cancelled)* ...
    cancelledRun.forceLimitN,'r--','LineWidth',1.4, ...
    'DisplayName','Cancelled state (scaled)');
hold off; grid on;
xlabel('Virtual time (s)'); ylabel('Force (N)');
title('Cancellation purges queued commands before forcing safe zero');
legend('Location','best');

