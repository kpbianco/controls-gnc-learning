function run_checks
%RUN_CHECKS Verify P21 quintic equations, feasibility, limits, and failures.
tolerance = 5e-12;
baselineA = model(20,8,5,2,501);
baselineB = model(20,8,5,2,501);
assert(isequaln(baselineA,baselineB), ...
    'Repeated baseline calls must be exactly deterministic.');

% Independently reconstruct every sampled polynomial and derivative.
tau = linspace(0,1,501);
expectedPositionShape = 10*tau.^3-15*tau.^4+6*tau.^5;
expectedSpeedShape = 30*tau.^2-60*tau.^3+30*tau.^4;
expectedAccelerationShape = 60*tau-180*tau.^2+120*tau.^3;
expectedJerkShape = 60-360*tau+360*tau.^2;
expectedPositionM = 20*expectedPositionShape;
expectedSpeedMPerSec = 20/8*expectedSpeedShape;
expectedAccelerationMPerSec2 = 20/8^2*expectedAccelerationShape;
expectedJerkMPerSec3 = 20/8^3*expectedJerkShape;
assert(max(abs(baselineA.normalizedTime-tau)) < tolerance && ...
    max(abs(baselineA.timeSec-8*tau)) < tolerance, ...
    'The retained time grids must match the independent normalized grid.');
assert(max(abs(baselineA.positionM-expectedPositionM)) < tolerance && ...
    max(abs(baselineA.speedMPerSec-expectedSpeedMPerSec)) < tolerance && ...
    max(abs(baselineA.accelerationMPerSec2- ...
    expectedAccelerationMPerSec2)) < tolerance && ...
    max(abs(baselineA.jerkMPerSec3-expectedJerkMPerSec3)) < tolerance, ...
    'Position and all three derivatives must follow the explicit quintic.');

% Endpoint, midpoint, symmetry, and direction invariants do not depend on
% model-reported summary values.
midpointIndex = (baselineA.sampleCount+1)/2;
assert(baselineA.positionM(1) == 0 && ...
    baselineA.positionM(end) == 20 && ...
    baselineA.speedMPerSec(1) == 0 && ...
    baselineA.speedMPerSec(end) == 0 && ...
    baselineA.accelerationMPerSec2(1) == 0 && ...
    baselineA.accelerationMPerSec2(end) == 0, ...
    'The trajectory must retain exact rest-to-rest endpoint conditions.');
assert(abs(baselineA.positionM(midpointIndex)-10) < tolerance && ...
    abs(baselineA.speedMPerSec(midpointIndex)-4.6875) < tolerance && ...
    abs(baselineA.accelerationMPerSec2(midpointIndex)) < tolerance && ...
    abs(baselineA.jerkMPerSec3(midpointIndex)+1.171875) < tolerance, ...
    'Midpoint position and derivatives must match independent values.');
assert(max(abs(expectedPositionShape+fliplr(expectedPositionShape)-1)) < ...
    tolerance && ...
    max(abs(expectedSpeedShape-fliplr(expectedSpeedShape))) < tolerance && ...
    max(abs(expectedAccelerationShape+ ...
    fliplr(expectedAccelerationShape))) < tolerance && ...
    max(abs(expectedJerkShape-fliplr(expectedJerkShape))) < tolerance, ...
    'The quintic derivative symmetries must be preserved.');
assert(all(diff(baselineA.positionM) >= -tolerance) && ...
    min(baselineA.positionM) >= -tolerance && ...
    max(baselineA.positionM) <= 20+tolerance, ...
    'A positive target must move monotonically inside the endpoint hull.');

% Analytic peaks and feasibility bounds are independent of the plot grid.
expectedPeakSpeed = 15*20/(8*8);
expectedPeakAcceleration = 10*sqrt(3)*20/(3*8^2);
expectedPeakJerk = 60*20/8^3;
accelerationPeakTau = [(3-sqrt(3))/6 (3+sqrt(3))/6];
accelerationAtPeaks = 20/8^2*(60*accelerationPeakTau- ...
    180*accelerationPeakTau.^2+120*accelerationPeakTau.^3);
assert(abs(baselineA.analyticPeakSpeedMPerSec-expectedPeakSpeed) < ...
    tolerance && ...
    abs(baselineA.analyticPeakAccelerationMPerSec2- ...
    max(abs(accelerationAtPeaks))) < tolerance && ...
    abs(baselineA.analyticPeakAccelerationMPerSec2- ...
    expectedPeakAcceleration) < tolerance && ...
    abs(baselineA.analyticPeakJerkMPerSec3-expectedPeakJerk) < ...
    tolerance, ...
    'Analytic speed, acceleration, and jerk peaks must match calculus.');
assert(baselineA.sampledPeakSpeedMPerSec == expectedPeakSpeed && ...
    baselineA.sampledPeakAccelerationMPerSec2 < ...
    baselineA.analyticPeakAccelerationMPerSec2 && ...
    baselineA.sampledPeakJerkMPerSec3 == expectedPeakJerk, ...
    'Sampled plots must not replace the off-grid analytic acceleration peak.');

expectedSpeedDuration = 15*20/(8*5);
expectedAccelerationDuration = sqrt(10*sqrt(3)*20/(3*2));
assert(abs(baselineA.minimumDurationFromSpeedSec- ...
    expectedSpeedDuration) < tolerance && ...
    abs(baselineA.minimumDurationFromAccelerationSec- ...
    expectedAccelerationDuration) < tolerance && ...
    abs(baselineA.minimumFeasibleDurationSec- ...
    max(expectedSpeedDuration,expectedAccelerationDuration)) < tolerance && ...
    strcmp(baselineA.activeConstraint,'acceleration') && ...
    baselineA.speedFeasible && baselineA.accelerationFeasible && ...
    baselineA.feasible, ...
    'Baseline feasibility must use the larger exact duration bound.');
assert(abs(baselineA.analyticPeakSpeedMPerSec-4.6875) < tolerance && ...
    abs(baselineA.analyticPeakAccelerationMPerSec2- ...
    1.8042195912175802) < tolerance && ...
    abs(baselineA.minimumFeasibleDurationSec- ...
    7.598356856515925) < tolerance, ...
    'Baseline reference metrics must remain deterministic.');

% Independent distance sweep: all non-swept values reset and peaks scale
% linearly, while minimum duration uses max(linear,square-root) bounds.
targetPositionValuesM = [5 10 15 20 25];
for k = 1:numel(targetPositionValuesM)
    changed = model(targetPositionValuesM(k),8,5,2,501);
    expectedDistance = targetPositionValuesM(k);
    expectedDistancePeakSpeed = 15*expectedDistance/(8*8);
    expectedDistancePeakAcceleration = 10*sqrt(3)*expectedDistance/ ...
        (3*8^2);
    expectedDistanceMinimum = max(15*expectedDistance/(8*5), ...
        sqrt(10*sqrt(3)*expectedDistance/(3*2)));
    assert(changed.moveDurationSec == 8 && ...
        changed.maximumSpeedMPerSec == 5 && ...
        changed.maximumAccelerationMPerSec2 == 2 && ...
        changed.sampleCount == 501, ...
        'Distance sweep must reset every non-swept input.');
    assert(abs(changed.analyticPeakSpeedMPerSec- ...
        expectedDistancePeakSpeed) < tolerance && ...
        abs(changed.analyticPeakAccelerationMPerSec2- ...
        expectedDistancePeakAcceleration) < tolerance && ...
        abs(changed.minimumFeasibleDurationSec- ...
        expectedDistanceMinimum) < tolerance, ...
        'Distance-sweep demands must match independent formulas.');
end
assert(model(20,8,5,2,501).feasible && ...
    ~model(25,8,5,2,501).feasible, ...
    'Distance sweep must cross the declared feasibility boundary.');

% Independent duration sweep and exact chain-rule scaling.
moveDurationValuesSec = [4 6 8 10 12];
for k = 1:numel(moveDurationValuesSec)
    changed = model(20,moveDurationValuesSec(k),5,2,501);
    expectedDuration = moveDurationValuesSec(k);
    assert(changed.targetPositionM == 20 && ...
        changed.maximumSpeedMPerSec == 5 && ...
        changed.maximumAccelerationMPerSec2 == 2 && ...
        changed.sampleCount == 501, ...
        'Duration sweep must reset every non-swept input.');
    assert(abs(changed.analyticPeakSpeedMPerSec- ...
        15*20/(8*expectedDuration)) < tolerance && ...
        abs(changed.analyticPeakAccelerationMPerSec2- ...
        10*sqrt(3)*20/(3*expectedDuration^2)) < tolerance && ...
        abs(changed.analyticPeakJerkMPerSec3- ...
        60*20/expectedDuration^3) < tolerance, ...
        'Duration-sweep demands must follow first-, second-, and third powers.');
end
twiceDuration = model(20,16,5,2,501);
assert(abs(twiceDuration.analyticPeakSpeedMPerSec- ...
    baselineA.analyticPeakSpeedMPerSec/2) < tolerance && ...
    abs(twiceDuration.analyticPeakAccelerationMPerSec2- ...
    baselineA.analyticPeakAccelerationMPerSec2/4) < tolerance && ...
    abs(twiceDuration.analyticPeakJerkMPerSec3- ...
    baselineA.analyticPeakJerkMPerSec3/8) < tolerance, ...
    'Doubling duration must give exact 1/T, 1/T^2, and 1/T^3 scaling.');

% Exact active-constraint limits and a just-below-bound rejection.
speedBoundaryDuration = 15*25/(8*5);
speedBoundary = model(25,speedBoundaryDuration,5,20,501);
speedBelowBoundary = model(25,speedBoundaryDuration-1e-6,5,20,501);
assert(strcmp(speedBoundary.activeConstraint,'speed') && ...
    speedBoundary.feasible && speedBoundary.speedFeasible && ...
    abs(speedBoundary.speedUtilization-1) < tolerance && ...
    ~speedBelowBoundary.speedFeasible && ~speedBelowBoundary.feasible, ...
    'The exact speed-derived duration is feasible and a shorter move is not.');
accelerationBoundaryDuration = sqrt(10*sqrt(3)*5/(3*2));
accelerationBoundary = model(5,accelerationBoundaryDuration,20,2,501);
accelerationBelowBoundary = model(5, ...
    accelerationBoundaryDuration-1e-6,20,2,501);
assert(strcmp(accelerationBoundary.activeConstraint,'acceleration') && ...
    accelerationBoundary.feasible && ...
    accelerationBoundary.accelerationFeasible && ...
    abs(accelerationBoundary.accelerationUtilization-1) < tolerance && ...
    ~accelerationBelowBoundary.accelerationFeasible && ...
    ~accelerationBelowBoundary.feasible, ...
    'The exact acceleration-derived duration is feasible and a shorter move is not.');
tieDuration = 15*20/(8*5);
tieAccelerationLimit = 10*sqrt(3)*20/(3*tieDuration^2);
tieBoundary = model(20,tieDuration,5,tieAccelerationLimit,501);
assert(strcmp(tieBoundary.activeConstraint,'tie') && ...
    tieBoundary.feasible && ...
    abs(tieBoundary.speedUtilization-1) < tolerance && ...
    abs(tieBoundary.accelerationUtilization-1) < tolerance, ...
    'Equal speed and acceleration duration bounds must report a feasible tie.');

% Direction, zero-distance, broken request, stateless recovery, and grids.
reverse = model(-20,8,5,2,501);
assert(max(abs(reverse.positionM+baselineA.positionM)) < tolerance && ...
    max(abs(reverse.speedMPerSec+baselineA.speedMPerSec)) < tolerance && ...
    max(abs(reverse.accelerationMPerSec2+ ...
    baselineA.accelerationMPerSec2)) < tolerance && ...
    max(abs(reverse.jerkMPerSec3+baselineA.jerkMPerSec3)) < tolerance && ...
    reverse.minimumFeasibleDurationSec == ...
    baselineA.minimumFeasibleDurationSec && reverse.feasible, ...
    'Reversing direction must preserve absolute demand and feasibility.');
zeroDistance = model(0,2,0.5,0.1,51);
assert(all(zeroDistance.positionM == 0) && ...
    all(zeroDistance.speedMPerSec == 0) && ...
    all(zeroDistance.accelerationMPerSec2 == 0) && ...
    all(zeroDistance.jerkMPerSec3 == 0) && ...
    zeroDistance.minimumFeasibleDurationSec == 0 && ...
    zeroDistance.speedUtilization == 0 && ...
    zeroDistance.accelerationUtilization == 0 && ...
    strcmp(zeroDistance.activeConstraint,'none') && zeroDistance.feasible, ...
    'Zero distance must be an exact stationary limiting case.');
broken = model(20,4,5,2,501);
recovered = model(20,8,5,2,501);
assert(abs(broken.analyticPeakSpeedMPerSec-9.375) < tolerance && ...
    abs(broken.analyticPeakAccelerationMPerSec2- ...
    7.216878364870321) < tolerance && ...
    ~broken.speedFeasible && ~broken.accelerationFeasible && ...
    ~broken.feasible && strcmp(broken.feasibilityStatus,'infeasible'), ...
    'The smooth 4 s request must visibly violate both named constraints.');
assert(isequaln(recovered,baselineA), ...
    'A fresh valid call must exactly recover the baseline after failure.');
coarse = model(20,8,5,2,51);
fine = model(20,8,5,2,5001);
assert(coarse.analyticPeakSpeedMPerSec == ...
    fine.analyticPeakSpeedMPerSec && ...
    coarse.analyticPeakAccelerationMPerSec2 == ...
    fine.analyticPeakAccelerationMPerSec2 && ...
    coarse.minimumFeasibleDurationSec == fine.minimumFeasibleDurationSec && ...
    coarse.feasible == fine.feasible, ...
    'Sampling resolution must not change analytic feasibility.');

% Malformed inputs and resource bounds fail before trajectory allocation.
assertAnyError(@() model(NaN,8,5,2,501), ...
    'A nonfinite target must be rejected.');
assertAnyError(@() model([20 20],8,5,2,501), ...
    'A nonscalar target must be rejected.');
assertAnyError(@() model(20+1i,8,5,2,501), ...
    'A complex target must be rejected.');
assertAnyError(@() model(20,NaN,5,2,501), ...
    'A nonfinite duration must be rejected.');
assertAnyError(@() model(20,8,Inf,2,501), ...
    'A nonfinite speed limit must be rejected.');
assertAnyError(@() model(20,8,5,2,500.5), ...
    'A noninteger sample count must be rejected.');
assertErrorId(@() model(30.01,8,5,2,501), ...
    'P21:TargetPositionRange','Excessive target must fail.');
assertErrorId(@() model(-30.01,8,5,2,501), ...
    'P21:TargetPositionRange','Excessive reverse target must fail.');
assertErrorId(@() model(20,1.99,5,2,501), ...
    'P21:DurationRange','Too-short duration must fail.');
assertErrorId(@() model(20,20.01,5,2,501), ...
    'P21:DurationRange','Excessive duration must fail.');
assertErrorId(@() model(20,8,0.49,2,501), ...
    'P21:SpeedLimitRange','Too-small speed limit must fail.');
assertErrorId(@() model(20,8,20.01,2,501), ...
    'P21:SpeedLimitRange','Excessive speed limit must fail.');
assertErrorId(@() model(20,8,5,0.09,501), ...
    'P21:AccelerationLimitRange','Too-small acceleration limit must fail.');
assertErrorId(@() model(20,8,5,20.01,501), ...
    'P21:AccelerationLimitRange','Excessive acceleration limit must fail.');
assertErrorId(@() model(20,8,5,2,50), ...
    'P21:SampleCountRange','Too-small sample count must fail.');
assertErrorId(@() model(20,8,5,2,5002), ...
    'P21:SampleCountRange','Oversized sample count must fail before allocation.');

boundedGrid = model(30,20,20,20,5001);
assert(boundedGrid.sampleCount == 5001 && ...
    numel(boundedGrid.timeSec) == 5001 && ...
    all(isfinite(boundedGrid.positionM)) && ...
    all(isfinite(boundedGrid.speedMPerSec)) && ...
    all(isfinite(boundedGrid.accelerationMPerSec2)) && ...
    all(isfinite(boundedGrid.jerkMPerSec3)) && boundedGrid.feasible, ...
    'The largest accepted history must remain finite and bounded.');

disp(['P21 checks passed: deterministic quintic histories, analytic ' ...
    'peaks, exact duration limits, two isolated sweeps, infeasibility, ' ...
    'stateless recovery, malformed inputs, and resource bounds.']);
end

function assertAnyError(operation,message)
didError = false;
try
    operation();
catch
    didError = true;
end
assert(didError,message);
end

function assertErrorId(operation,expectedIdentifier,message)
actualIdentifier = '';
try
    operation();
catch exception
    actualIdentifier = exception.identifier;
end
assert(strcmp(actualIdentifier,expectedIdentifier),message);
end
