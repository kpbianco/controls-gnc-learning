function result = model(targetPositionM,moveDurationSec, ...
    maximumSpeedMPerSec,maximumAccelerationMPerSec2,sampleCount)
%MODEL Generate and assess one transparent rest-to-rest quintic trajectory.
arguments
    targetPositionM (1,1) double {mustBeReal,mustBeFinite} = 20
    moveDurationSec (1,1) double ...
        {mustBeReal,mustBeFinite,mustBePositive} = 8
    maximumSpeedMPerSec (1,1) double ...
        {mustBeReal,mustBeFinite,mustBePositive} = 5
    maximumAccelerationMPerSec2 (1,1) double ...
        {mustBeReal,mustBeFinite,mustBePositive} = 2
    sampleCount (1,1) double ...
        {mustBeReal,mustBeFinite,mustBeInteger,mustBePositive} = 501
end

if abs(targetPositionM) > 30
    error('P21:TargetPositionRange', ...
        'Target position must be between -30 and 30 metres.');
end
if moveDurationSec < 2 || moveDurationSec > 20
    error('P21:DurationRange', ...
        'Move duration must be between 2 and 20 seconds.');
end
if maximumSpeedMPerSec < 0.5 || maximumSpeedMPerSec > 20
    error('P21:SpeedLimitRange', ...
        'Maximum speed must be between 0.5 and 20 m/s.');
end
if maximumAccelerationMPerSec2 < 0.1 || ...
        maximumAccelerationMPerSec2 > 20
    error('P21:AccelerationLimitRange', ...
        'Maximum acceleration must be between 0.1 and 20 m/s^2.');
end
minimumSampleCount = 51;
maximumSampleCount = 5001;
if sampleCount < minimumSampleCount || sampleCount > maximumSampleCount
    error('P21:SampleCountRange', ...
        'Sample count must be an integer between 51 and 5001.');
end

% The bounds above run before allocating any trajectory history.
normalizedTime = linspace(0,1,sampleCount);
timeSec = moveDurationSec*normalizedTime;

% Rest-to-rest quintic and its first three normalized derivatives.
positionShape = 10*normalizedTime.^3-15*normalizedTime.^4+ ...
    6*normalizedTime.^5;
speedShape = 30*normalizedTime.^2-60*normalizedTime.^3+ ...
    30*normalizedTime.^4;
accelerationShape = 60*normalizedTime-180*normalizedTime.^2+ ...
    120*normalizedTime.^3;
jerkShape = 60-360*normalizedTime+360*normalizedTime.^2;

positionM = targetPositionM*positionShape;
speedMPerSec = targetPositionM/moveDurationSec*speedShape;
accelerationMPerSec2 = targetPositionM/moveDurationSec^2* ...
    accelerationShape;
jerkMPerSec3 = targetPositionM/moveDurationSec^3*jerkShape;

travelDistanceM = abs(targetPositionM);
peakSpeedNormalizedTime = 0.5;
accelerationExtremaNormalizedTime = ...
    [(3-sqrt(3))/6 (3+sqrt(3))/6];
analyticPeakSpeedMPerSec = 15*travelDistanceM/(8*moveDurationSec);
analyticPeakAccelerationMPerSec2 = 10*sqrt(3)*travelDistanceM/ ...
    (3*moveDurationSec^2);
analyticPeakJerkMPerSec3 = 60*travelDistanceM/moveDurationSec^3;
sampledPeakSpeedMPerSec = max(abs(speedMPerSec));
sampledPeakAccelerationMPerSec2 = max(abs(accelerationMPerSec2));
sampledPeakJerkMPerSec3 = max(abs(jerkMPerSec3));

minimumDurationFromSpeedSec = 15*travelDistanceM/ ...
    (8*maximumSpeedMPerSec);
minimumDurationFromAccelerationSec = sqrt(10*sqrt(3)*travelDistanceM/ ...
    (3*maximumAccelerationMPerSec2));
minimumFeasibleDurationSec = max(minimumDurationFromSpeedSec, ...
    minimumDurationFromAccelerationSec);
speedUtilization = analyticPeakSpeedMPerSec/maximumSpeedMPerSec;
accelerationUtilization = analyticPeakAccelerationMPerSec2/ ...
    maximumAccelerationMPerSec2;
ratioTolerance = 64*eps(max([1 speedUtilization accelerationUtilization]));
speedFeasible = speedUtilization <= 1+ratioTolerance;
accelerationFeasible = accelerationUtilization <= 1+ratioTolerance;
feasible = speedFeasible && accelerationFeasible;

durationToleranceSec = 64*eps(max([1 minimumDurationFromSpeedSec ...
    minimumDurationFromAccelerationSec]));
if travelDistanceM == 0
    activeConstraint = 'none';
elseif abs(minimumDurationFromSpeedSec- ...
        minimumDurationFromAccelerationSec) <= durationToleranceSec
    activeConstraint = 'tie';
elseif minimumDurationFromSpeedSec > minimumDurationFromAccelerationSec
    activeConstraint = 'speed';
else
    activeConstraint = 'acceleration';
end

if speedFeasible
    speedStatus = 'within limit';
else
    speedStatus = 'violated';
end
if accelerationFeasible
    accelerationStatus = 'within limit';
else
    accelerationStatus = 'violated';
end
if feasible
    feasibilityStatus = 'feasible';
else
    feasibilityStatus = 'infeasible';
end

result = struct( ...
    'targetPositionM',targetPositionM, ...
    'travelDistanceM',travelDistanceM, ...
    'moveDurationSec',moveDurationSec, ...
    'maximumSpeedMPerSec',maximumSpeedMPerSec, ...
    'maximumAccelerationMPerSec2',maximumAccelerationMPerSec2, ...
    'minimumSampleCount',minimumSampleCount, ...
    'maximumSampleCount',maximumSampleCount, ...
    'sampleCount',sampleCount, ...
    'normalizedTime',normalizedTime, ...
    'timeSec',timeSec, ...
    'positionShape',positionShape, ...
    'speedShape',speedShape, ...
    'accelerationShape',accelerationShape, ...
    'jerkShape',jerkShape, ...
    'positionM',positionM, ...
    'speedMPerSec',speedMPerSec, ...
    'accelerationMPerSec2',accelerationMPerSec2, ...
    'jerkMPerSec3',jerkMPerSec3, ...
    'peakSpeedNormalizedTime',peakSpeedNormalizedTime, ...
    'accelerationExtremaNormalizedTime', ...
    accelerationExtremaNormalizedTime, ...
    'analyticPeakSpeedMPerSec',analyticPeakSpeedMPerSec, ...
    'analyticPeakAccelerationMPerSec2', ...
    analyticPeakAccelerationMPerSec2, ...
    'analyticPeakJerkMPerSec3',analyticPeakJerkMPerSec3, ...
    'sampledPeakSpeedMPerSec',sampledPeakSpeedMPerSec, ...
    'sampledPeakAccelerationMPerSec2', ...
    sampledPeakAccelerationMPerSec2, ...
    'sampledPeakJerkMPerSec3',sampledPeakJerkMPerSec3, ...
    'minimumDurationFromSpeedSec',minimumDurationFromSpeedSec, ...
    'minimumDurationFromAccelerationSec', ...
    minimumDurationFromAccelerationSec, ...
    'minimumFeasibleDurationSec',minimumFeasibleDurationSec, ...
    'durationMarginSec',moveDurationSec-minimumFeasibleDurationSec, ...
    'speedUtilization',speedUtilization, ...
    'accelerationUtilization',accelerationUtilization, ...
    'ratioTolerance',ratioTolerance, ...
    'speedFeasible',speedFeasible, ...
    'accelerationFeasible',accelerationFeasible, ...
    'feasible',feasible, ...
    'activeConstraint',activeConstraint, ...
    'speedStatus',speedStatus, ...
    'accelerationStatus',accelerationStatus, ...
    'feasibilityStatus',feasibilityStatus, ...
    'endpointPositionResidualM',positionM(end)-targetPositionM, ...
    'endpointSpeedResidualMPerSec',speedMPerSec(end), ...
    'endpointAccelerationResidualMPerSec2',accelerationMPerSec2(end));
end
