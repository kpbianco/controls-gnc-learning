function interactive
%INTERACTIVE Explore P21 trajectory time scaling and constraint feasibility.
modelFunction = @model;

window = uifigure('Name','P21 - Feasible trajectory generation', ...
    'Position',[100 100 1180 760]);
positionAxes = uiaxes(window,'Position',[50 520 690 190]);
speedAxes = uiaxes(window,'Position',[50 285 690 190]);
accelerationAxes = uiaxes(window,'Position',[50 50 690 190]);

uilabel(window,'Position',[780 680 340 22], ...
    'Text','Target position from zero (m)');
targetSlider = uislider(window,'Position',[785 660 310 3], ...
    'Limits',[-30 30],'Value',20, ...
    'MajorTicks',[-30 -20 -10 0 10 20 30]);

uilabel(window,'Position',[780 610 340 22], ...
    'Text','Move duration (s)');
durationSlider = uislider(window,'Position',[785 590 310 3], ...
    'Limits',[2 20],'Value',8,'MajorTicks',[2 4 8 12 16 20]);

uilabel(window,'Position',[780 535 190 22], ...
    'Text','Speed limit (m/s)');
speedLimitSpinner = uispinner(window,'Position',[990 535 105 22], ...
    'Limits',[0.5 20],'Step',0.5,'Value',5);

uilabel(window,'Position',[780 490 210 22], ...
    'Text','Acceleration limit (m/s^2)');
accelerationLimitSpinner = uispinner(window, ...
    'Position',[990 490 105 22], ...
    'Limits',[0.1 20],'Step',0.1,'Value',2);

resetButton = uibutton(window,'push','Text','Reset feasible baseline', ...
    'Position',[780 440 315 30]);
statusLabel = uilabel(window,'Position',[780 65 350 345], ...
    'VerticalAlignment','top','WordWrap','on','Text','');

targetSlider.ValueChangingFcn = @(~,event) redraw(event.Value, ...
    durationSlider.Value,speedLimitSpinner.Value, ...
    accelerationLimitSpinner.Value);
targetSlider.ValueChangedFcn = @(~,~) redraw(targetSlider.Value, ...
    durationSlider.Value,speedLimitSpinner.Value, ...
    accelerationLimitSpinner.Value);
durationSlider.ValueChangingFcn = @(~,event) redraw(targetSlider.Value, ...
    event.Value,speedLimitSpinner.Value,accelerationLimitSpinner.Value);
durationSlider.ValueChangedFcn = @(~,~) redraw(targetSlider.Value, ...
    durationSlider.Value,speedLimitSpinner.Value, ...
    accelerationLimitSpinner.Value);
speedLimitSpinner.ValueChangedFcn = @(~,~) redraw(targetSlider.Value, ...
    durationSlider.Value,speedLimitSpinner.Value, ...
    accelerationLimitSpinner.Value);
accelerationLimitSpinner.ValueChangedFcn = @(~,~) redraw( ...
    targetSlider.Value,durationSlider.Value,speedLimitSpinner.Value, ...
    accelerationLimitSpinner.Value);
resetButton.ButtonPushedFcn = @(~,~) resetBaseline();

redraw(20,8,5,2);

function resetBaseline
    targetSlider.Value = 20;
    durationSlider.Value = 8;
    speedLimitSpinner.Value = 5;
    accelerationLimitSpinner.Value = 2;
    redraw(20,8,5,2);
end

function redraw(targetPosition,duration,speedLimit,accelerationLimit)
    result = modelFunction(targetPosition,duration,speedLimit, ...
        accelerationLimit,501);

    cla(positionAxes);
    plot(positionAxes,result.timeSec,result.positionM,'b-', ...
        'LineWidth',1.8);
    grid(positionAxes,'on');
    xlabel(positionAxes,'Time (s)');
    ylabel(positionAxes,'Position (m)');
    title(positionAxes,'Rest-to-rest quintic reference');

    cla(speedAxes);
    plot(speedAxes,result.timeSec,result.speedMPerSec,'m-', ...
        'LineWidth',1.8,'DisplayName','Trajectory speed');
    hold(speedAxes,'on');
    yline(speedAxes,speedLimit,'r:','Positive speed limit');
    yline(speedAxes,-speedLimit,'r:','Negative speed limit');
    hold(speedAxes,'off'); grid(speedAxes,'on');
    xlabel(speedAxes,'Time (s)'); ylabel(speedAxes,'Speed (m/s)');
    title(speedAxes,'Speed demand and declared limit');
    legend(speedAxes,'Location','best');

    cla(accelerationAxes);
    plot(accelerationAxes,result.timeSec,result.accelerationMPerSec2, ...
        'c-','LineWidth',1.8,'DisplayName','Trajectory acceleration');
    hold(accelerationAxes,'on');
    yline(accelerationAxes,accelerationLimit,'r:', ...
        'Positive acceleration limit');
    yline(accelerationAxes,-accelerationLimit,'r:', ...
        'Negative acceleration limit');
    hold(accelerationAxes,'off'); grid(accelerationAxes,'on');
    xlabel(accelerationAxes,'Time (s)');
    ylabel(accelerationAxes,'Acceleration (m/s^2)');
    title(accelerationAxes,'Acceleration demand and declared limit');
    legend(accelerationAxes,'Location','best');

    if result.travelDistanceM == 0
        interpretation = ['zero-distance limit: the reference stays at ' ...
            'rest and no kinematic constraint is active'];
    elseif ~result.feasible
        interpretation = ['infeasible: increase duration, relax a limit, ' ...
            'or shorten the move'];
    elseif result.durationMarginSec < 0.25
        interpretation = ['feasible but close to the active duration ' ...
            'boundary; sampled plots do not replace analytic peaks'];
    else
        interpretation = ['feasible kinematic reference; plant tracking and ' ...
            'obstacle clearance remain separate questions'];
    end
    statusLabel.Text = sprintf([ ...
        '%s\n\ntarget: %.2f m\nduration: %.2f s\n' ...
        'active minimum-duration constraint: %s\n' ...
        'minimum feasible duration: %.4f s\nmargin: %.4f s\n\n' ...
        'peak speed: %.4f m/s (%.1f%%, %s)\n' ...
        'peak acceleration: %.4f m/s^2 (%.1f%%, %s)\n' ...
        'peak jerk: %.4f m/s^3\n\n%s'], ...
        upper(result.feasibilityStatus),targetPosition,duration, ...
        result.activeConstraint,result.minimumFeasibleDurationSec, ...
        result.durationMarginSec,result.analyticPeakSpeedMPerSec, ...
        100*result.speedUtilization,result.speedStatus, ...
        result.analyticPeakAccelerationMPerSec2, ...
        100*result.accelerationUtilization,result.accelerationStatus, ...
        result.analyticPeakJerkMPerSec3,interpretation);
end
end
